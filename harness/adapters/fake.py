"""
Fake Agent Adapter para Harness v2.3
Utilizado para testes contratuais e simulações de fluxo de governança.
"""
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional

from harness.adapters.base import AgentCapabilities, BaseAgentAdapter, CollectionBundle
from harness.core.context_pack import ContextPack
from harness.core.execution_pack import ExecutionPack


class FakeAgentAdapter(BaseAgentAdapter):
    def __init__(
        self,
        project_root: Optional[str | Path] = None,
        exit_code: int = 0,
        files_to_modify: Optional[List[str]] = None,
        stdout: str = "Fake execution completed successfully.",
        stderr: str = "",
        capabilities: Optional[AgentCapabilities] = None,
    ):
        super().__init__(project_root)
        self.default_exit_code = exit_code
        self.default_files_to_modify = files_to_modify or []
        self.default_stdout = stdout
        self.default_stderr = stderr
        self.capabilities = capabilities or AgentCapabilities(
            interactive=True,
            headless=True,
            supports_streaming=False,
            supports_tools=True,
        )
        self.execution_history: List[Dict[str, Any]] = []

    def get_capabilities(self) -> AgentCapabilities:
        return self.capabilities

    def execute(
        self,
        execution_pack: ExecutionPack,
        context_pack: ContextPack,
        timeout_seconds: int = 300,
    ) -> CollectionBundle:
        run_id = f"fake-run-{execution_pack.pack_id}"

        # Simula escrita dos arquivos se especificado
        for f in self.default_files_to_modify:
            target = self.root / f
            target.parent.mkdir(parents=True, exist_ok=True)
            if not target.exists():
                target.write_text(f"# Generated by FakeAgentAdapter for {execution_pack.pack_id}\n", encoding="utf-8")

        record = {
            "run_id": run_id,
            "pack_id": execution_pack.pack_id,
            "context_pack_id": context_pack.pack_id,
            "timeout_seconds": timeout_seconds,
        }
        self.execution_history.append(record)

        return CollectionBundle(
            run_id=run_id,
            adapter_name="fake",
            exit_code=self.default_exit_code,
            files_modified=list(self.default_files_to_modify),
            stdout=self.default_stdout,
            stderr=self.default_stderr,
            metadata={"history_index": len(self.execution_history) - 1},
        )
